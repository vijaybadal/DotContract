// Prepends a "generated" banner to the precompiled stylesheet used on StackBlitz.
import { readFileSync, writeFileSync } from "node:fs";
const f = "src/app/globals.prebuilt.css";
const css = readFileSync(f, "utf8").replace(/^\/\* GENERATED[\s\S]*?\*\/\n/, "");
writeFileSync(f, `/* GENERATED by \`npm run css:prebuilt\` from globals.css — do not edit. Used on StackBlitz, where Tailwind's native compiler can't run. Re-run after changing UI classes. */\n${css}`);
